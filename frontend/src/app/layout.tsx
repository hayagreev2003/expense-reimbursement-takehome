import type { Metadata } from 'next';
import { Geist, Geist_Mono } from 'next/font/google';
import './globals.css';
import { Providers } from './providers';

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

export const metadata: Metadata = {
  title: 'Nortex Travel Expense Settlement',
  description: 'Turn a trip inbox into a policy-checked expense claim.',
};

// Typed explicitly rather than with Next's generated LayoutProps global: that type only
// exists once .next/types has been written by a build, so `tsc --noEmit` on a clean
// checkout - which is exactly what CI runs - would not find it.
export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}>
      <body className="min-h-full flex flex-col">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
